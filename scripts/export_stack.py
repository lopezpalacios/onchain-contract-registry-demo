#!/usr/bin/env python3
"""Export the static registry and its SQLite source for a public gist.

The bundle is text-only. ``registry.sql`` rebuilds the SQLite database, and
``scripts/export_static.py`` regenerates ``web/data.js``. The browser needs
only HTML, CSS, and JavaScript.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

FILES = [
    "README.md",
    "REBUILD.md",
    "PROMPT.md",
    "PSTACK.md",
    "NOTICE.md",
    "index.html",
    "app.py",
    "registry.sql",
    "registry/keccak.py",
    "scripts/build_db.py",
    "scripts/export_static.py",
    "scripts/besu_sync.py",
    "scripts/business_case.py",
    "tests/test_registry.py",
    "web/index.html",
    "web/style.css",
    "web/app.js",
    "web/static-api.js",
    "docs/registry-blueprint.md",
    "docs/persona-review.md",
    "docs/platform-guide.md",
    "docs/firefly-kaleido-integration.md",
    "docs/business-case.md",
    "docs/example-queries.sql",
]

GIST_FILES = [
    ("README.md", "README.md"),
    ("REBUILD.md", "REBUILD.md"),
    ("PROMPT.md", "PROMPT.md"),
    ("PSTACK.md", "PSTACK.md"),
    ("docs/platform-guide.md", "PLATFORM-GUIDE.md"),
    ("registry.sql", "registry.sql"),
    ("dist/gist/MANIFEST.md", "MANIFEST.md"),
    ("dist/gist/STACK.md", "STACK.md"),
]

LANG = {
    ".py": "python",
    ".sql": "sql",
    ".js": "javascript",
    ".css": "css",
    ".html": "html",
    ".md": "markdown",
    ".json": "json",
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build(output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    missing = [name for name in FILES if not (ROOT / name).is_file()]
    if missing:
        raise SystemExit(f"missing files: {', '.join(missing)}")

    generated = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# Smart Contract Registry — static source bundle",
        "",
        "The product runtime uses HTML, CSS, and JavaScript only. SQLite is the build-time source of truth.",
        "",
        "This bundle contains the full source and the combined SQLite file. Use `REBUILD.md` for the build steps.",
        "",
        f"Generated: {generated}",
        "",
        "## Rebuild",
        "",
        "```bash",
        "mkdir -p data registry scripts web tests docs",
        "sqlite3 data/registry.db < registry.sql",
        "python3 scripts/export_static.py",
        "open web/index.html",
        "```",
        "",
        "Python is needed only for the build and the optional tests. The browser does not need a server.",
        "",
        "## File tree",
        "",
        "```text",
        "onchain-contract-registry-demo/",
        "├── README.md",
        "├── REBUILD.md",
        "├── PROMPT.md",
        "├── PSTACK.md",
        "├── NOTICE.md",
        "├── index.html",
        "├── registry.sql                  # schema + views + seed",
        "├── app.py                        # build/test read models (not runtime)",
        "├── registry/",
        "│   └── keccak.py",
        "├── scripts/",
        "│   ├── build_db.py",
        "│   ├── export_static.py          # SQLite -> web/data.js",
        "│   ├── besu_sync.py",
        "│   ├── business_case.py",
        "│   └── export_stack.py",
        "├── tests/",
        "│   └── test_registry.py",
        "├── web/",
        "│   ├── index.html                # static entry point",
        "│   ├── style.css",
        "│   ├── app.js",
        "│   ├── static-api.js             # browser API + localStorage",
        "│   └── data.js                   # generated by export_static.py",
        "└── docs/",
        "    ├── platform-guide.md         # why / what / how (ASD-STE100)",
        "    ├── registry-blueprint.md",
        "    ├── persona-review.md",
        "    ├── firefly-kaleido-integration.md",
        "    ├── business-case.md",
        "    └── example-queries.sql",
        "```",
        "",
        "---",
        "",
    ]

    manifest = [
        "# Source manifest",
        "",
        f"Generated: {generated}",
        "",
        "| File | Lines | SHA-256 |",
        "|---|---:|---|",
    ]

    for name in FILES:
        path = ROOT / name
        content = path.read_text(encoding="utf-8")
        line_count = content.count("\n") + (0 if content.endswith("\n") else 1)
        manifest.append(f"| `{name}` | {line_count} | `{sha256(path)}` |")
        suffix = path.suffix
        language = LANG.get(suffix, "text")
        lines.extend([
            f"## `{name}`",
            "",
            f"```````{language}",
            content.rstrip("\n"),
            "```````",
            "",
        ])

    lines.extend([
        "## License / status",
        "",
        "Fictional demo only. No real bank, customer or production data. Not production-ready. No bank affiliation. Add a licence appropriate to your organisation before reuse.",
        "",
    ])

    (output_dir / "STACK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (output_dir / "MANIFEST.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")

    for source, name in GIST_FILES:
        source_path = ROOT / source
        target_path = output_dir / name
        if source_path.resolve() != target_path.resolve():
            shutil.copyfile(source_path, target_path)

    print(f"wrote {output_dir / 'STACK.md'} ({((output_dir / 'STACK.md').stat().st_size / 1024):.1f} KiB)")
    print(f"wrote {output_dir / 'MANIFEST.md'}")
    print(f"wrote {len(GIST_FILES)} gist files to {output_dir}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "dist" / "gist")
    args = parser.parse_args()
    build(args.output)


if __name__ == "__main__":
    main()
