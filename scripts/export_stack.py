#!/usr/bin/env python3
"""Export the runnable stack into a self-contained Markdown bundle for a gist.

The bundle is intentionally text-only: the SQLite database is rebuilt with
``python3 scripts/build_db.py``. This keeps the gist readable and avoids
publishing a binary artefact.
"""

from __future__ import annotations

import argparse
import hashlib
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

FILES = [
    "README.md",
    "PROMPT.md",
    "PSTACK.md",
    "NOTICE.md",
    "app.py",
    "registry/schema.sql",
    "registry/views.sql",
    "registry/seed.sql",
    "registry/keccak.py",
    "scripts/build_db.py",
    "scripts/besu_sync.py",
    "scripts/business_case.py",
    "tests/test_registry.py",
    "web/index.html",
    "web/style.css",
    "web/app.js",
    "docs/registry-blueprint.md",
    "docs/persona-review.md",
    "docs/business-case.md",
    "docs/example-queries.sql",
]

LANG = {
    ".py": "python",
    ".sql": "sql",
    ".js": "javascript",
    ".css": "css",
    ".html": "html",
    ".md": "markdown",
    ".json": "json",
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build(output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    missing = [name for name in FILES if not (ROOT / name).is_file()]
    if missing:
        raise SystemExit(f"missing files: {', '.join(missing)}")

    lines = [
        "# Financial Institution Smart Contract Registry — full source bundle",
        "",
        "This is the text-only source bundle for the public demo. It is intended to be copied into a coding agent or cloned from the companion GitHub repository.",
        "",
        f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        "",
        "## Reconstruct",
        "",
        "```bash",
        "mkdir -p registry scripts web tests docs data",
        "python3 scripts/build_db.py",
        "python3 app.py",
        "```",
        "",
        "Create each file at the path shown in its heading. The SQLite database is generated, not included.",
        "",
        "## File tree",
        "",
        "```text",
        "onchain-contract-registry-demo/",
        "├── README.md",
        "├── PROMPT.md",
        "├── PSTACK.md",
        "├── NOTICE.md",
        "├── app.py",
        "├── registry/",
        "│   ├── schema.sql",
        "│   ├── views.sql",
        "│   ├── seed.sql",
        "│   └── keccak.py",
        "├── scripts/",
        "│   ├── build_db.py",
        "│   ├── besu_sync.py",
        "│   ├── business_case.py",
        "│   └── export_stack.py",
        "├── tests/",
        "│   └── test_registry.py",
        "├── web/",
        "│   ├── index.html",
        "│   ├── style.css",
        "│   └── app.js",
        "├── docs/",
        "│   ├── registry-blueprint.md",
        "│   ├── persona-review.md",
        "│   ├── business-case.md",
        "│   └── example-queries.sql",
        "└── data/registry.db   # generated by build_db.py",
        "```",
        "",
        "---",
        "",
    ]

    manifest = [
        "# Source manifest",
        "",
        f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        "",
        "| File | Lines | SHA-256 |",
        "|---|---:|---|",
    ]

    for name in FILES:
        path = ROOT / name
        content = path.read_text(encoding="utf-8")
        line_count = content.count("\n") + (0 if content.endswith("\n") else 1)
        manifest.append(f"| `{name}` | {line_count} | `{sha256(path)}` |")
        suffix = path.suffix
        language = LANG.get(suffix, "text")
        lines.extend([
            f"## `{name}`",
            "",
            f"```````{language}",
            content.rstrip("\n"),
            "```````",
            "",
        ])

    lines.extend([
        "## License / status",
        "",
        "Fictional demo only. No real bank, customer or production data. Not production-ready. No bank affiliation. Add a licence appropriate to your organisation before reuse.",
        "",
    ])

    (output_dir / "STACK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (output_dir / "MANIFEST.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print(f"wrote {output_dir / 'STACK.md'} ({((output_dir / 'STACK.md').stat().st_size / 1024):.1f} KiB)")
    print(f"wrote {output_dir / 'MANIFEST.md'}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "dist" / "gist")
    args = parser.parse_args()
    build(args.output)


if __name__ == "__main__":
    main()
